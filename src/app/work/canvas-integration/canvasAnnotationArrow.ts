/** Figma hand-drawn annotation arrows — head + body split from combined export paths. */

export type AnnotationArrow = {
  bodyPath: string;
  headPath: string;
  combinedPath: string;
};

/** Split a Figma combined arrow path (`head…ZMbody…`) into fillable subpaths. */
function parseFigmaAnnotationArrow(combinedPath: string): AnnotationArrow {
  const splitAt = combinedPath.indexOf("ZM");
  if (splitAt === -1) {
    throw new Error("Expected Figma annotation arrow path with head/body subpaths");
  }

  return {
    headPath: combinedPath.slice(0, splitAt + 1),
    bodyPath: combinedPath.slice(splitAt + 2),
    combinedPath,
  };
}

/** Full hand-drawn arrow (body + head) as exported from Figma. */
export function annotationArrowPath(arrow: AnnotationArrow): string {
  return arrow.combinedPath;
}

/** Closed fill path for the arrowhead triangle. */
export function annotationArrowheadPath(arrow: AnnotationArrow): string {
  return arrow.headPath;
}

